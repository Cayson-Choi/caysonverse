/**
 * scripts/extract-seat-markers.ts — village.glb의 좌석 표시(`seat__*` 빈 노드)를 TypeScript 목록으로 뽑는다.
 *
 *   npx tsx --tsconfig server/tsconfig.json scripts/extract-seat-markers.ts client/public/models/village/village.glb shared/src/village/generated/villageSeatMarkers.ts
 *
 * Blender 빌드(parts_cafe.py `seat_markers`, parts_buildings.py 포치 벤치)가 의자·벤치마다 `seat__<id>__..._face<n|s|e|w>`
 * 빈 노드를 두고, 굽기(bake_village.py `patch_glb`)가 사용자 속성(seatTop, approach, frontEdge, standX/standZ, length, places)을
 * 노드 extras로 넣는다. 이 스크립트는 그 값을 그대로 옮겨 적고(0.001 단위), shared/src/village/benchSeats.ts가 앉을 자리로 만든다.
 * 그림과 좌석 데이터가 어긋나지 않게(설계 4: "Blender에서 좌석 위치를 표시해 두면 데이터가 자동으로 만들어져요").
 * 회전·부모가 있거나 extras가 빠지면 FAIL(종료 코드 1)이고 파일을 쓰지 않는다. 같은 입력이면 출력은 바이트 단위로 같다.
 */

import fs from "node:fs";
import { parseGlb } from "./lib/schoolGlb";

const USAGE = "usage: npx tsx --tsconfig server/tsconfig.json scripts/extract-seat-markers.ts <glb> <out.ts>";

interface Marker {
  id: string;
  x: number;
  z: number;
  facing: "n" | "s" | "e" | "w";
  seatTop: number;
  approach: "front" | "side";
  frontEdge: number;
  length?: number;
  places: number;
  standX?: number;
  standZ?: number;
}

const r3 = (v: number): number => Math.round(v * 1000) / 1000;

export function extractSeatMarkers(gltf: { nodes?: Array<Record<string, unknown>> }): { markers: Marker[]; problems: string[] } {
  const markers: Marker[] = [];
  const problems: string[] = [];
  const children = new Set<number>();
  for (const n of gltf.nodes ?? []) for (const c of (n.children as number[] | undefined) ?? []) children.add(c);
  (gltf.nodes ?? []).forEach((n, i) => {
    const name = String(n.name ?? "");
    const m = /^seat__(.+?)__.*_face([nsew])$/.exec(name);
    if (!m) return;
    const ex = (n.extras ?? {}) as Record<string, unknown>;
    const t = n.translation as number[] | undefined;
    if (!t) problems.push(`${name}: translation 없음`);
    if (n.rotation || n.matrix) problems.push(`${name}: 회전/matrix가 있어요`);
    if (!children.has(i)) {
      // a root node: fine
    } else problems.push(`${name}: 부모 노드 아래에 있어요`);
    const num = (k: string): number | undefined => (typeof ex[k] === "number" ? (ex[k] as number) : undefined);
    const approach = ex.approach === "side" ? "side" : ex.approach === "front" ? "front" : undefined;
    const seatTop = num("seatTop");
    const frontEdge = num("frontEdge");
    if (!approach || seatTop === undefined || frontEdge === undefined) {
      problems.push(`${name}: extras에 approach/seatTop/frontEdge가 없어요 (bake_village.py patch_glb)`);
      return;
    }
    const mk: Marker = {
      id: m[1]!,
      x: r3(t?.[0] ?? 0),
      z: r3(t?.[2] ?? 0),
      facing: m[2] as Marker["facing"],
      seatTop: r3(seatTop),
      approach,
      frontEdge: r3(frontEdge),
      places: num("places") ?? 1,
    };
    const len = num("length");
    if (len !== undefined) mk.length = r3(len);
    if (approach === "side") {
      const sx = num("standX");
      const sz = num("standZ");
      if (sx === undefined || sz === undefined) problems.push(`${name}: 옆 접근 좌석에 standX/standZ가 없어요`);
      else {
        mk.standX = r3(sx);
        mk.standZ = r3(sz);
      }
    }
    markers.push(mk);
  });
  const nat = (s: string): (string | number)[] => s.split(/(\d+)/).map((p, k) => (k % 2 ? Number(p) : p));
  markers.sort((a, b) => {
    const A = nat(a.id);
    const B = nat(b.id);
    for (let k = 0; k < Math.max(A.length, B.length); k++) {
      if (A[k] === B[k]) continue;
      if (A[k] === undefined) return -1;
      if (B[k] === undefined) return 1;
      return typeof A[k] === "number" && typeof B[k] === "number" ? (A[k] as number) - (B[k] as number) : String(A[k]) < String(B[k]) ? -1 : 1;
    }
    return 0;
  });
  return { markers, problems };
}

export function renderSeatMarkerModule(markers: readonly Marker[]): string {
  const lines = [
    "// GENERATED by scripts/extract-seat-markers.ts — 손으로 고치지 않는다",
    "// village.glb의 seat__* 노드(Blender의 좌석 표시)에서 뽑은 의자·벤치. benchSeats.ts가 앉을 자리로 만든다.",
    "// 모델을 고치면 `npx tsx --tsconfig server/tsconfig.json scripts/extract-seat-markers.ts`로 다시 만든다.",
    "",
    'import type { VillageSeatMarker } from "../benchSeats";',
    "",
    "export const VILLAGE_SEAT_MARKERS: readonly VillageSeatMarker[] = [",
  ];
  for (const m of markers) {
    const parts = [
      `id: ${JSON.stringify(m.id)}`,
      `x: ${m.x}`,
      `z: ${m.z}`,
      `facing: ${JSON.stringify(m.facing)}`,
      `seatTop: ${m.seatTop}`,
      `approach: ${JSON.stringify(m.approach)}`,
      `frontEdge: ${m.frontEdge}`,
      `places: ${m.places}`,
    ];
    if (m.length !== undefined) parts.push(`length: ${m.length}`);
    if (m.standX !== undefined) parts.push(`standX: ${m.standX}`, `standZ: ${m.standZ}`);
    lines.push(`  { ${parts.join(", ")} },`);
  }
  lines.push("];", "");
  return lines.join("\n");
}

export function main(argv: string[]): number {
  const [glbPath, outFile] = argv;
  if (!glbPath || !outFile || argv.length !== 2) {
    console.error(USAGE);
    return 1;
  }
  const gltf = parseGlb(fs.readFileSync(glbPath)).gltf as { nodes?: Array<Record<string, unknown>> };
  const { markers, problems } = extractSeatMarkers(gltf);
  if (markers.length === 0) problems.push("seat__* 노드가 하나도 없어요");
  if (problems.length) {
    for (const p of problems) console.error(`FAIL: ${p}`);
    return 1;
  }
  fs.writeFileSync(outFile, renderSeatMarkerModule(markers));
  console.log(`좌석 표시 ${markers.length}개 → ${outFile}`);
  return 0;
}

if (require.main === module) process.exit(main(process.argv.slice(2)));
