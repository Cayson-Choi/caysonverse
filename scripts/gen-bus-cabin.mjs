/**
 * GENERATED-FILE MAKER: the bus's cabin data (seats, walk solids, seat backs, floor steps, the driver's place) from
 * art/village/export/village_bus_cabin.json (written by build_bus.py, the same run that writes village_bus.glb) into
 * shared/src/village/generated/busCabin.ts. The TypeScript never re-derives the model.
 *
 *   node scripts/gen-bus-cabin.mjs <village_bus_cabin.json> shared/src/village/generated/busCabin.ts
 */
import fs from "node:fs";

const [src, out] = process.argv.slice(2);
if (!src || !out) {
  console.error("usage: node scripts/gen-bus-cabin.mjs <cabin.json> <out.ts>");
  process.exit(2);
}
const d = JSON.parse(fs.readFileSync(src, "utf8"));
const r = (n) => Math.round(n * 1000) / 1000;
const num = (n) => String(r(n));
const seats = d.seats.map((s) => `  { id: "${s.id}", ahead: ${num(s.ahead)}, right: ${num(s.right)}, floor: ${num(s.floor)}, yaw: ${num(s.yaw)}, backed: ${s.backed} },`).join("\n");
const backs = d.seatBacks.map((s) => `  { seat: "${s.seat}", min: [${s.min.map(num).join(", ")}], max: [${s.max.map(num).join(", ")}] },`).join("\n");
const solids = d.solids.map((s) => `  { id: "${s.id}", minAhead: ${num(s.min[0])}, minRight: ${num(s.min[1])}, maxAhead: ${num(s.max[0])}, maxRight: ${num(s.max[1])} },`).join("\n");
const floor = d.floor.map((s) => `  { xf0: ${num(s.xf0)}, xf1: ${num(s.xf1)}, h: ${num(s.h)} },`).join("\n");
const dr = d.driver;
const text = `/**
 * GENERATED by scripts/gen-bus-cabin.mjs from art/village/export/village_bus_cabin.json (build_bus.py): do not edit by hand.
 * The bus's cabin in the bus's own frame: \`ahead\` along its heading from the middle of the footprint, \`right\` towards the
 * doors (+x of the model), heights from the ground; \`yaw\` is the avatar's facing relative to the bus (the world yaw's offset: 0 =
 * forward, -PI/2 = towards the doors).
 */

export interface GenSeat { id: string; ahead: number; right: number; floor: number; yaw: number; backed: boolean }
export interface GenSeatBack { seat: string; min: readonly [number, number, number]; max: readonly [number, number, number] }
export interface GenSolid { id: string; minAhead: number; minRight: number; maxAhead: number; maxRight: number }
export interface GenFloor { xf0: number; xf1: number; h: number }

export const GEN_CABIN_SEATS: readonly GenSeat[] = [
${seats}
];

export const GEN_CABIN_SEAT_BACKS: readonly GenSeatBack[] = [
${backs}
];

export const GEN_CABIN_SOLIDS: readonly GenSolid[] = [
${solids}
];

/** The floor's heights by xf (m back from the front face): the low floor, the two steps' treads, the raised rear. */
export const GEN_CABIN_FLOOR: readonly GenFloor[] = [
${floor}
];

export const GEN_CABIN_CEILING = ${num(d.ceiling)};
export const GEN_CABIN_HALF_WIDTH = ${num(d.innerHalfWidth)};
export const GEN_CABIN_BOUNDS = { aheadMin: ${num(d.bounds.aheadMin)}, aheadMax: ${num(d.bounds.aheadMax)}, right: ${num(d.bounds.right)} } as const;
/** The two doors' xf spans (front, middle). */
export const GEN_CABIN_DOORS: readonly (readonly [number, number])[] = [${d.doors.map((x) => `[${x.map(num).join(", ")}]`).join(", ")}];
/**
 * The driver's place (nodes bus_driver_seat, bus_steering_wheel, bus_driver_sit in village_bus.glb): the seat's centre on the
 * floor (its cushion's top \`surface\` m above the floor), where a sitter's root goes, and the steering wheel's hub (\`y\` up,
 * its axis tilted back \`tiltDeg\` from vertical towards the driver).
 */
export const GEN_CABIN_DRIVER = {
  seat: { ahead: ${num(dr.seat.ahead)}, right: ${num(dr.seat.right)}, floor: ${num(dr.seat.floor)}, surface: ${num(dr.seat.surface)} },
  sit: { ahead: ${num(dr.sit.ahead)}, right: ${num(dr.sit.right)}, floor: ${num(dr.sit.floor)} },
  wheel: { ahead: ${num(dr.wheel.ahead)}, right: ${num(dr.wheel.right)}, y: ${num(dr.wheel.y)}, tiltDeg: ${num(dr.wheel.tiltDeg)}, radius: ${num(dr.wheel.radius)} },
} as const;
`;
fs.writeFileSync(out, text);
console.log(`wrote ${out}: ${d.seats.length} seats, ${d.solids.length} solids`);
