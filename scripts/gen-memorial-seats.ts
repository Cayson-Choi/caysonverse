/**
 * scripts/gen-memorial-seats.ts — 추모관 모델의 `seat__*` 표식(Blender)에서 앉는 자리 자료를 만든다 (2026-11-13 추모관 새로 짓기).
 *
 *   npx tsx scripts/gen-memorial-seats.ts <memorial_seats.json> [out.ts]
 *
 * 입력은 art/village/tools/bake_memorial.py가 쓰는 `export/memorial_seats.json`(표식 하나당 한 줄: 가구 종류, 등받이 있음/없음, 앉는 면의
 * 가운데 x·z·높이, 앉은 사람이 보는 쪽, 앞 가장자리까지, 등받이까지, 좌석 폭, 겹침 묶음, 양쪽에서 앉기, 일어서는 쪽, 기대는 정도).
 * 출력은 shared/src/village/generated/memorialSeats.ts: `benchSeats.ts`가 이것으로 클라이언트와 서버가 함께 쓰는 한 줄짜리 자리 목록
 * (`VILLAGE_SEATS`)을 만든다. 같은 입력이면 출력은 바이트 단위로 같다. 의존성 없음.
 */

import fs from "node:fs";
import path from "node:path";

const REPO = path.resolve(__dirname, "..");
const DEFAULT_OUT = path.join(REPO, "shared", "src", "village", "generated", "memorialSeats.ts");
const USAGE = "usage: npx tsx scripts/gen-memorial-seats.ts <memorial_seats.json> [out.ts]";

const FURN = ["bench", "sofa", "armchair", "chair"] as const;
const KIND = ["backless", "backed"] as const;

interface RawSeat {
  id: string;
  furn: string;
  kind: string;
  x: number;
  z: number;
  y: number;
  yaw: number;
  edge: number;
  back: number;
  width: number;
  group: string;
  both: number | boolean;
  exit_turn: number;
  lean: number;
}

const r3 = (v: number): number => Math.round(v * 1000) / 1000;
/** Angles keep 6 decimals: 3.142 would be past pi. */
const r6 = (v: number): number => Math.round(v * 1e6) / 1e6;

export function render(seats: readonly RawSeat[]): string {
  const sorted = [...seats].sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  const lines = sorted.map((s) => {
    if (!(FURN as readonly string[]).includes(s.furn)) throw new Error(`${s.id}: 알 수 없는 가구 ${s.furn}`);
    if (!(KIND as readonly string[]).includes(s.kind)) throw new Error(`${s.id}: 알 수 없는 종류 ${s.kind}`);
    for (const k of ["x", "z", "y", "yaw", "edge", "back", "width", "exit_turn", "lean"] as const) {
      if (!Number.isFinite(s[k])) throw new Error(`${s.id}: ${k}가 숫자가 아니에요`);
    }
    if (s.kind === "backed" && !(s.back > 0)) throw new Error(`${s.id}: 등받이 있는 자리인데 등받이까지의 거리가 없어요`);
    return (
      `  { id: ${JSON.stringify(s.id)}, furn: ${JSON.stringify(s.furn)}, kind: ${JSON.stringify(s.kind)}, x: ${r3(s.x)}, z: ${r3(s.z)}, y: ${r3(s.y)}, ` +
      `yaw: ${r6(s.yaw)}, edge: ${r3(s.edge)}, back: ${r3(s.back)}, width: ${r3(s.width)}, group: ${JSON.stringify(s.group)}, ` +
      `both: ${s.both ? "true" : "false"}, exitTurn: ${r6(s.exit_turn)}, lean: ${r3(s.lean)} },`
    );
  });
  return [
    "// GENERATED by scripts/gen-memorial-seats.ts — 손으로 고치지 않는다",
    "// memorial.glb를 만든 Blender 장면의 seat__* 표식에서 뽑은 앉는 자리(가구 하나의 자리 하나). benchSeats.ts가 이것으로 자리 목록을 만든다.",
    "// 모델을 고치면 bake_memorial.py가 export/memorial_seats.json을 다시 쓰고, `npx tsx scripts/gen-memorial-seats.ts <그 파일>`로 다시 만든다.",
    "",
    'import type { SeatMarker } from "../seatMarkers";',
    "",
    "export const MEMORIAL_SEAT_MARKERS: readonly SeatMarker[] = [",
    ...lines,
    "];",
    "",
  ].join("\n");
}

export function main(argv: string[]): number {
  const [input, out] = argv;
  if (!input || argv.length > 2) {
    console.error(USAGE);
    return 1;
  }
  let raw: { seats: RawSeat[] };
  try {
    raw = JSON.parse(fs.readFileSync(input, "utf8"));
  } catch (err) {
    console.error(`FAIL: ${input}를 읽지 못했어요: ${(err as Error).message}`);
    return 1;
  }
  let text: string;
  try {
    text = render(raw.seats);
  } catch (err) {
    console.error(`FAIL: ${(err as Error).message}`);
    return 1;
  }
  const outFile = path.resolve(out ?? DEFAULT_OUT);
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, text, "utf8");
  console.log(`PASS: 앉는 자리 표식 ${raw.seats.length}개 → ${outFile}`);
  return 0;
}

if (require.main === module) process.exit(main(process.argv.slice(2)));
