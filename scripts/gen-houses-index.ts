/**
 * scripts/gen-houses-index.ts — shared/src/village/generated/houses/index.ts 를 만든다 (집 실내 G, 2026-11-16).
 *
 *   npx tsx scripts/gen-houses-index.ts            # 폴더를 훑어 index.ts를 다시 쓴다
 *   npx tsx scripts/gen-houses-index.ts --check    # 쓰지 않고, 지금 index.ts가 폴더와 같은지만 확인(다르면 종료 코드 1)
 *
 * house_N_seats.ts(HOUSE_N_SEAT_MARKERS)와 house_N_colliders.ts(HOUSE_N_COLLIDERS, HOUSE_N_CAMERA_BOXES)가 **둘 다** 있는 집만 목록에
 * 들어간다. 그 밖의 집은 게임에서 문이 잠긴 채로 있다(번호키 "아직 준비 중이에요"). HA·HB는 index.ts를 고치지 않는다 — 집을
 * 끝내고 생성 파일 두 개를 커밋한 다음 이 스크립트를 한 번 돌리면 새 집이 게임에 들어온다(시험이 index.ts가 폴더와 같은지 지켜본다).
 * 같은 입력이면 출력은 바이트 단위로 같다.
 */

import fs from "node:fs";
import path from "node:path";

const DIR = path.resolve(__dirname, "../shared/src/village/generated/houses");
export const INDEX_FILE = path.join(DIR, "index.ts");

/** The house numbers (1..10, ascending) that have both generated files with their exports. */
export function generatedHouseNumbers(dir: string = DIR): number[] {
  const out: number[] = [];
  for (let n = 1; n <= 10; n++) {
    const seats = path.join(dir, `house_${n}_seats.ts`);
    const cols = path.join(dir, `house_${n}_colliders.ts`);
    if (!fs.existsSync(seats) || !fs.existsSync(cols)) continue;
    const s = fs.readFileSync(seats, "utf8");
    const c = fs.readFileSync(cols, "utf8");
    if (!s.includes(`HOUSE_${n}_SEAT_MARKERS`) || !c.includes(`HOUSE_${n}_COLLIDERS`) || !c.includes(`HOUSE_${n}_CAMERA_BOXES`)) continue;
    out.push(n);
  }
  return out;
}

/** The text of index.ts for these houses. */
export function renderIndex(numbers: readonly number[]): string {
  const lines: string[] = [];
  lines.push("// GENERATED by scripts/gen-houses-index.ts — 손으로 고치지 않는다");
  lines.push("// 이 폴더의 house_N_seats.ts / house_N_colliders.ts 가운데 둘 다 있는 집의 목록. 새 집이 들어오면 `npx tsx scripts/gen-houses-index.ts`.");
  lines.push("");
  lines.push('import type { AABB, CameraBox } from "../../../collision";');
  lines.push('import type { HouseNumber, HouseSeatMarker } from "../../houseAreas";');
  for (const n of numbers) {
    lines.push(`import { HOUSE_${n}_SEAT_MARKERS } from "./house_${n}_seats";`);
    lines.push(`import { HOUSE_${n}_CAMERA_BOXES, HOUSE_${n}_COLLIDERS } from "./house_${n}_colliders";`);
  }
  lines.push("");
  lines.push("/** What the game knows of one finished house: its seat markers, its collision boxes and the camera boxes (≥ 1.6 m tall). */");
  lines.push("export interface GeneratedHouse {");
  lines.push("  readonly seats: readonly HouseSeatMarker[];");
  lines.push("  readonly colliders: readonly AABB[];");
  lines.push("  readonly cameraBoxes: readonly CameraBox[];");
  lines.push("}");
  lines.push("");
  lines.push("/** The finished houses by number; a house that is not here has no interior yet (its door stays locked). */");
  lines.push("export const GENERATED_HOUSES: Readonly<Partial<Record<HouseNumber, GeneratedHouse>>> = {");
  for (const n of numbers) lines.push(`  ${n}: { seats: HOUSE_${n}_SEAT_MARKERS, colliders: HOUSE_${n}_COLLIDERS, cameraBoxes: HOUSE_${n}_CAMERA_BOXES },`);
  lines.push("};");
  lines.push("");
  lines.push("/** The numbers of the finished houses, ascending. */");
  lines.push(`export const GENERATED_HOUSE_NUMBERS: readonly HouseNumber[] = [${numbers.join(", ")}];`);
  lines.push("");
  return lines.join("\n");
}

if (require.main === module) {
  const text = renderIndex(generatedHouseNumbers());
  if (process.argv.includes("--check")) {
    const have = fs.existsSync(INDEX_FILE) ? fs.readFileSync(INDEX_FILE, "utf8").replace(/\r\n/g, "\n") : "";
    if (have !== text) {
      console.error("FAIL: generated/houses/index.ts가 폴더와 달라요 — `npx tsx scripts/gen-houses-index.ts`");
      process.exit(1);
    }
    console.log("PASS: index.ts가 폴더와 같아요");
  } else {
    fs.writeFileSync(INDEX_FILE, text);
    console.log(`wrote ${path.relative(process.cwd(), INDEX_FILE)} (houses: ${generatedHouseNumbers().join(", ") || "none"})`);
  }
}
