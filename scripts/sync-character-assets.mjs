#!/usr/bin/env node
/**
 * scripts/sync-character-assets.mjs — 캐릭터 자산을 게임으로 가져온다 (캐릭터 3단계 Task 2).
 *
 *   node scripts/sync-character-assets.mjs [--art <dir>]      (기본값: <repo>/art/character)
 *
 * art/ 는 gitignore 대상이고 main 체크아웃에만 있다. 워크트리에서는 --art 로 그 경로를 넘긴다.
 * 하는 일:
 *   1. check-character-glb.mjs 를 <art>/export/character.glb 와 character.manifest.json 에 돌린다. 실패하면 종료 코드 1.
 *   2. manifest 의 draco 가 false 가 아니면 종료 코드 1 (Draco GLB 는 디코더가 필요하다).
 *   3. 복사한다 (원본이 모두 있고 점검이 끝난 뒤에만 쓴다).
 *        <art>/export/character.glb              → client/public/models/character.glb
 *        <art>/../brand/cayson-logo-white.png    → client/public/brand/cayson-logo-white.png  (조립실 제목 전용)
 *   4. shared/src/characterManifest.ts 를 쓰고 복사한 파일 크기를 출력한다. 이 파일에는 GLB 내용의 sha256 앞 8자리
 *      (CHARACTER_GLB_HASH)도 들어간다: 클라이언트가 모델 URL에 ?v=<hash>로 붙여, 새 GLB를 배포하면 브라우저·CDN에
 *      남은 옛 GLB 대신 새 것을 받는다.
 * 같은 입력으로 다시 돌리면 결과 파일이 바이트 단위로 같다(멱등).
 *
 * 부품 순서 규칙(append only): manifest slots의 부품 순서가 곧 외형 필드 값(부품 인덱스)이다. 그 값은 동기화되고
 * 서버 재접속 캐시와 localStorage["cv.entry"]에 저장되므로, 새 부품은 그 슬롯 끝에만 덧붙인다(끼워 넣기·지우기·순서
 * 바꾸기 금지). shared/src/appearance.test.ts의 "slot part order" 고정값이 어긋나면 실패한다.
 */

import { createHash } from "node:crypto";
import { copyFileSync, existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "..");

function fail(message) {
  console.error(`FAIL: ${message}`);
  process.exit(1);
}

function parseArgs(argv) {
  let art = resolve(REPO, "art/character");
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === "--art") {
      const value = argv[i + 1];
      if (!value) fail("--art needs a directory\nusage: node scripts/sync-character-assets.mjs [--art <dir>]");
      art = resolve(value);
      i += 1;
    } else {
      fail(`unknown argument ${argv[i]}\nusage: node scripts/sync-character-assets.mjs [--art <dir>]`);
    }
  }
  return art;
}

const art = parseArgs(process.argv.slice(2));
const srcGlb = resolve(art, "export/character.glb");
const srcManifest = resolve(art, "export/character.manifest.json");
const srcLogo = resolve(art, "../brand/cayson-logo-white.png");
const dstGlb = resolve(REPO, "client/public/models/character.glb");
const dstLogo = resolve(REPO, "client/public/brand/cayson-logo-white.png");
const dstTs = resolve(REPO, "shared/src/characterManifest.ts");

for (const file of [srcGlb, srcManifest, srcLogo]) {
  if (!existsSync(file)) fail(`missing source file ${file}`);
}

// 1. GLB ↔ manifest 점검 (부품·클립·변형 클립·투구·NPC 전용·크기).
const check = spawnSync(process.execPath, [resolve(REPO, "scripts/check-character-glb.mjs"), srcGlb, srcManifest], {
  stdio: "inherit",
});
if (check.error) fail(`could not run check-character-glb.mjs: ${check.error.message}`);
if (check.status !== 0) fail("check-character-glb.mjs did not pass — nothing was copied");

// 2. Draco 금지.
let manifest;
try {
  manifest = JSON.parse(readFileSync(srcManifest, "utf8"));
} catch (err) {
  fail(`cannot read ${srcManifest}: ${err.message}`);
}
if (manifest.draco !== false) fail("Draco GLB는 디코더가 필요 — 발주자 승인 전 금지");

// 4(먼저 만든다). 생성 TS. 키 순서는 manifest 그대로(조립실 슬롯 순서가 여기서 나온다).
// slots의 부품 순서 = 외형 필드 값(부품 인덱스)이다: append only(머리말 "부품 순서 규칙").
const glbHash = createHash("sha256").update(readFileSync(srcGlb)).digest("hex").slice(0, 8);
const ts = `// GENERATED by scripts/sync-character-assets.mjs — do not edit
// 원본: art/character/export/character.manifest.json (스키마·서버 코드를 import 하지 않는 브라우저 안전 모듈)

export interface CharacterManifestShape {
  slots: Record<string, readonly string[]>;
  slotLabels: Record<string, string>;
  labels: Record<string, Record<string, string>>;
  tintMaterials: Record<string, string>;
  defaultColors: Record<string, Record<string, string>>;
  covers: Record<string, string>;
  hatVariants: Record<string, string>;
  hairCut: number;
  hatHidesHair: readonly string[];
  npcOnly: Record<string, readonly string[]>;
  /** 동작 클립 이름: 기본 7개와 하의 변형(*_LongSkirt, *_ShortSkirt). */
  clips: readonly string[];
  /** 하의 부품 id → 기본 클립 → 변형 클립. 보폭은 유지하고 치마를 뚫지 않게 다리 움직임만 줄인다. */
  clipVariants: Record<string, Record<string, string>>;
  maxBytes: number;
  draco: boolean;
}

export const CHARACTER_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const satisfies CharacterManifestShape;

export type CharacterSlot = keyof typeof CHARACTER_MANIFEST.slots;

/** manifest slots 순서. */
export const CHARACTER_SLOTS: readonly CharacterSlot[] = Object.keys(CHARACTER_MANIFEST.slots) as CharacterSlot[];

/** 모든 아바타가 쓰는 공통 몸 메시. */
export const BODY_MESHES = ["body__head", "body__hands", "body__torso", "body__legs", "body__feet"] as const;

/** character.glb 내용의 sha256 앞 8자리. 클라이언트가 모델 URL에 ?v=로 붙인다(새 GLB를 배포하면 URL이 바뀐다). */
export const CHARACTER_GLB_HASH = "${glbHash}";
`;

// 3. 복사 + TS 쓰기.
mkdirSync(dirname(dstGlb), { recursive: true });
mkdirSync(dirname(dstLogo), { recursive: true });
copyFileSync(srcGlb, dstGlb);
copyFileSync(srcLogo, dstLogo);
writeFileSync(dstTs, ts, "utf8");

const rel = (p) => relative(REPO, p).replaceAll("\\", "/");
for (const file of [dstGlb, dstLogo]) {
  const bytes = statSync(file).size;
  console.log(`copied ${rel(file)}: ${(bytes / 1024 / 1024).toFixed(2)} MB (${bytes} bytes)`);
}
console.log(`wrote ${rel(dstTs)} (CHARACTER_GLB_HASH ${glbHash})`);
