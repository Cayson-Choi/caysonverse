def tl(sp):
    """total length (snout -> caudal tip) in SL units"""
    c = next(f for f in sp["FINS"] if f[0] == "C")
    return max(p[0] for p in c[2])


def yoff(sp):
    xs = np.linspace(0, 1, 101)
    return 0.5 * (pchip(sp["TOP"], xs).max() + pchip(sp["BOT"], xs).min())


def profiles(sp, x):
    top = pchip(sp["TOP"], x); bot = pchip(sp["BOT"], x); w = pchip(sp["WID"], x)
    wp = pchip(sp["WPOS"], x); nt = pchip(sp["NT"], x); nb = pchip(sp["NB"], x)
    return top, bot, w, wp, nt, nb


def section(sp, x, th):
    """x, th broadcastable arrays. th: 0 = back, pi = belly, (0, pi) = right side (+X). Returns X, Y, yc, h_up, h_dn."""
    top, bot, w, wp, nt, nb = profiles(sp, x)
    yc = bot + wp * (top - bot)
    s = np.cos(th); c = np.sin(th)
    up = s >= 0
    n = np.where(up, nt, nb)
    Y = np.where(up, yc + (top - yc) * spow(s, 2.0 / nt), yc + (yc - bot) * spow(s, 2.0 / nb))
    X = w * spow(c, 2.0 / n)
    return X, Y, yc, top, bot, w


def op_edge(sp, yn):
    """x of the gill-cover rear edge at normalized height yn (0 belly .. 1 back)."""
    ox, ob, _ = sp["OP"]
    yn = np.asarray(yn, dtype=np.float64)
    return ox + ob * (1 - ((yn - 0.55) / 0.5) ** 2) - 0.12 * np.clip(0.32 - yn, 0, None)


def seg_dist(px, py, ax, ay, bx, by):
    vx, vy = bx - ax, by - ay
    t = np.clip(((px - ax) * vx + (py - ay) * vy) / (vx * vx + vy * vy + 1e-12), 0, 1)
    return np.hypot(px - (ax + t * vx), py - (ay + t * vy)), t


def head_disp(sp, x, X, Y, top, bot, w):
    """Outward displacement (SL units) for head relief: raised gill-cover plate with a stepped rear edge, mouth gape groove."""
    yn = (Y - bot) / np.maximum(top - bot, 1e-6)
    _, _, oh = sp["OP"]
    xe = op_edge(sp, yn)
    vert = smoothstep(0.02, 0.14, yn) * (1 - smoothstep(0.78, 0.92, yn))
    lat = smoothstep(0.15, 0.5, np.abs(X) / np.maximum(w, 1e-6))
    plate = smoothstep(xe + 0.003, xe - 0.010, x) * smoothstep(xe - 0.16, xe - 0.08, x)
    groove = np.exp(-(((x - xe - 0.007) / 0.005) ** 2))
    d = oh * (plate - 0.45 * groove) * vert * lat
    gx, gy, gd, gw = sp["GAPE"]
    my = sp["MOUTH"]["y"]
    dist, t = seg_dist(x, Y, 0.0, my, gx, gy)
    g = np.exp(-((dist / gw) ** 2)) * smoothstep(0.25, 0.6, np.abs(X) / np.maximum(w, 1e-6))
    lip = np.exp(-(((dist - 1.6 * gw) / gw) ** 2)) * smoothstep(0.25, 0.6, np.abs(X) / np.maximum(w, 1e-6)) * (1 - t) ** 0.5
    d = d - gd * g + 0.25 * gd * lip
    return d
