def pchip(pts, x):
    """Monotone cubic (Fritsch-Carlson) through pts [(x, y)], clamped outside."""
    p = np.asarray(pts, dtype=np.float64)
    xs, ys = p[:, 0], p[:, 1]
    x = np.clip(np.asarray(x, dtype=np.float64), xs[0], xs[-1])
    n = len(xs)
    if n == 1:
        return np.full_like(x, ys[0])
    h = np.diff(xs); d = np.diff(ys) / h
    m = np.zeros(n)
    m[0] = d[0]; m[-1] = d[-1]
    for i in range(1, n - 1):
        if d[i - 1] * d[i] <= 0:
            m[i] = 0.0
        else:
            w1 = 2 * h[i] + h[i - 1]; w2 = h[i] + 2 * h[i - 1]
            m[i] = (w1 + w2) / (w1 / d[i - 1] + w2 / d[i])
    idx = np.clip(np.searchsorted(xs, x, side="right") - 1, 0, n - 2)
    t = (x - xs[idx]) / h[idx]
    t2 = t * t; t3 = t2 * t
    return ((2 * t3 - 3 * t2 + 1) * ys[idx] + (t3 - 2 * t2 + t) * h[idx] * m[idx]
            + (-2 * t3 + 3 * t2) * ys[idx + 1] + (t3 - t2) * h[idx] * m[idx + 1])


def spow(a, e):
    return np.sign(a) * np.abs(a) ** e


def smoothstep(a, b, x):
    t = np.clip((np.asarray(x, dtype=np.float64) - a) / (b - a), 0.0, 1.0)
    return t * t * (3 - 2 * t)


